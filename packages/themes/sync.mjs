// Refreshes themes.json from the MoCDTI shared platform: one theme per agency profile
// (agencies/<slug>/profile.json identity.legalName, shortName and themeColor). Fixtures are skipped.
//
//   pnpm run sync:themes            (platform at GGDS_PLATFORM_DIR, default ../agencies/platform)
//   pnpm run sync:themes -- --check (exit 1 if themes.json is out of date; the docs build runs this check too)
//
// themes.json is committed, so GGDS builds without the platform; this script only keeps it honest.
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { institutionColourProblems } from '../tokens/institution.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const themesPath = join(here, 'themes.json');
export const DEFAULT_THEME = 'mocdti';

export function platformDir() {
  return resolve(process.env.GGDS_PLATFORM_DIR ?? join(here, '..', '..', '..', 'agencies', 'platform'));
}

/** The themes as the platform's profiles define them today, or null when the platform is not available. */
export function themesFromPlatform(dir = platformDir()) {
  const agencies = join(dir, 'agencies');
  if (!existsSync(agencies)) return null;
  const themes = readdirSync(agencies, { withFileTypes: true })
    .filter((d) => d.isDirectory() && existsSync(join(agencies, d.name, 'profile.json')))
    .map((d) => ({ slug: d.name, profile: JSON.parse(readFileSync(join(agencies, d.name, 'profile.json'), 'utf8')) }))
    .filter(({ profile }) => profile.status !== 'fixture')
    .map(({ slug, profile: { identity, status } }) => {
      const problems = institutionColourProblems(identity.themeColor);
      if (problems.length) throw new Error(`${slug}: ${problems.join('; ')}`);
      return {
        slug,
        name: identity.legalName,
        shortName: identity.shortName,
        color: identity.themeColor.toLowerCase(),
        status,
        source: `agencies/${slug}/profile.json`,
      };
    })
    .sort((a, b) => (a.slug === DEFAULT_THEME ? -1 : b.slug === DEFAULT_THEME ? 1 : a.name.localeCompare(b.name)));
  if (!themes.some((t) => t.slug === DEFAULT_THEME)) throw new Error(`the platform has no ${DEFAULT_THEME} profile`);
  return {
    $description: 'GGDS institution themes. Generated by sync.mjs from the MoCDTI platform agency profiles; edit the profiles, not this file. Each theme sets only the institution colour (identity surfaces); links, buttons, forms and status stay shared.',
    default: DEFAULT_THEME,
    themes,
  };
}

const serialise = (data) => `${JSON.stringify(data, null, 2)}\n`;

/** [] when themes.json matches the platform; otherwise what differs. Null when the platform is not available. */
export function drift(dir = platformDir()) {
  const fresh = themesFromPlatform(dir);
  if (!fresh) return null;
  const current = JSON.parse(readFileSync(themesPath, 'utf8'));
  const byslug = (list) => new Map(list.map((t) => [t.slug, t]));
  const [a, b] = [byslug(current.themes), byslug(fresh.themes)];
  const out = [];
  for (const [slug, t] of b) {
    const c = a.get(slug);
    if (!c) out.push(`${slug}: in the platform, missing from themes.json`);
    else for (const k of ['name', 'shortName', 'color', 'status']) if (c[k] !== t[k]) out.push(`${slug}.${k}: themes.json "${c[k]}", platform "${t[k]}"`);
  }
  for (const slug of a.keys()) if (!b.has(slug)) out.push(`${slug}: in themes.json, not in the platform`);
  return out;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const dir = platformDir();
  if (process.argv.includes('--check')) {
    const d = drift(dir);
    if (d === null) { console.warn(`themes: platform not found at ${dir}; nothing to check`); process.exit(0); }
    if (d.length) { console.error(`themes.json is out of date with the platform (run pnpm run sync:themes):\n  ${d.join('\n  ')}`); process.exit(1); }
    console.log('themes: themes.json matches the platform');
  } else {
    const data = themesFromPlatform(dir);
    if (!data) { console.error(`themes: platform not found at ${dir} (set GGDS_PLATFORM_DIR)`); process.exit(1); }
    writeFileSync(themesPath, serialise(data));
    console.log(`themes: ${data.themes.length} themes from ${relative(process.cwd(), dir) || dir} → ${themesPath}`);
  }
}
