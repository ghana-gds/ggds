// Builds @ggds/themes from themes.json:
//   dist/<slug>.css     one theme for a whole site: <link rel="stylesheet" href="themes/nca.css"> after ggds.css
//   dist/themes.css     every theme, keyed by data-ggds-theme="<slug>" on <html> or on any element
//   dist/themes.json    every theme with its computed colours, for non-CSS tools
// Stylesheets, never inline styles: GGDS pages run under a CSP without 'unsafe-inline'.
import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { DEFAULT_THEME, allThemesCss, themeCss, themes } from './index.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const dist = join(here, 'dist');
rmSync(dist, { recursive: true, force: true });
mkdirSync(dist, { recursive: true });

const header = '/* Generated by @ggds/themes build.mjs from themes.json. Do not edit. */\n';
for (const t of themes) writeFileSync(join(dist, `${t.slug}.css`), header + themeCss(t.slug));
writeFileSync(join(dist, 'themes.css'), `${header}/* Default (no attribute): ${DEFAULT_THEME}, from @ggds/tokens. */\n${allThemesCss()}`);
writeFileSync(join(dist, 'themes.json'), `${JSON.stringify({ default: DEFAULT_THEME, themes }, null, 2)}\n`);

console.log(`themes: ${themes.length} themes (default ${DEFAULT_THEME}) → ${dist}`);
