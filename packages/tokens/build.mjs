// Builds the token outputs from tokens.json:
//   dist/tokens.css       CSS custom properties (--ggds-*), durations zeroed under prefers-reduced-motion
//   dist/tokens.json      { "--ggds-name": "resolved value" } for non-CSS tools
//   dist/compat-site.css  --site-* aliases, so the MoCDTI platform can switch to GGDS without renaming (one major version)
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { cssName, cssValue, flatten, loadTokens, resolveAll } from './lib.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const tokens = resolveAll(flatten(loadTokens(join(here, 'tokens.json'))));
const dist = join(here, 'dist');
mkdirSync(dist, { recursive: true });

const header = '/* Generated by @ggds/tokens build.mjs from tokens.json. Do not edit. */\n';
const lines = [...tokens.values()].map((t) => `  ${cssName(t.path)}: ${cssValue(t, tokens)};`);
const durations = [...tokens.values()].filter((t) => t.type === 'duration').map((t) => `    ${cssName(t.path)}: 0ms;`);

writeFileSync(join(dist, 'tokens.css'), `${header}:root {\n${lines.join('\n')}\n}\n\n@media (prefers-reduced-motion: reduce) {\n  :root {\n${durations.join('\n')}\n  }\n}\n`);

const flat = Object.fromEntries([...tokens.values()].map((t) => [cssName(t.path), Array.isArray(t.resolved) ? t.resolved : t.resolved]));
writeFileSync(join(dist, 'tokens.json'), `${JSON.stringify(flat, null, 2)}\n`);

