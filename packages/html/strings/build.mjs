// Builds GGDS's own text for every package from one source: en.json (English) and <code>.json (each language in
// languages.json). Writes:
//   packages/react/src/strings.ts                     STRINGS, TRANSLATIONS, LANGUAGES and stringsFor() for @ggds/react
//   packages/astro/src/strings.mjs                    the same for @ggds/astro
//   packages/django/src/ggds_django/strings.json      English and the language list for ggds-django
//   packages/django/src/ggds_django/locale/<code>/LC_MESSAGES/django.po and .mo
//                                                     gettext catalogues, so Django's own language switching works
// Each catalogue entry has its key as context (msgctxt), so the same English word in two places ("Next" page, "Next"
// stage) can be translated differently. The .mo files are written here, so the build does not need GNU gettext.
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const packages = join(here, '..', '..');
const read = (f) => JSON.parse(readFileSync(join(here, f), 'utf8'));
const strip = (o) => Object.fromEntries(Object.entries(o).filter(([k]) => !k.startsWith('$')));

export const STRINGS = strip(read('en.json'));
export const { languages: LANGUAGES } = read('languages.json');
export const TRANSLATIONS = Object.fromEntries(LANGUAGES.filter((l) => l.code !== 'en').map((l) => [l.code, strip(read(`${l.code}.json`))]));

const placeholders = (s) => [...s.matchAll(/\{(\w+)\}/g)].map((m) => m[1]).sort().join(',');
// A translation must have the same placeholders as the English, or a link or a number would go missing.
for (const [code, t] of Object.entries(TRANSLATIONS)) {
  for (const [key, text] of Object.entries(t)) {
    if (!(key in STRINGS)) throw new Error(`strings: ${code}.json has "${key}", which en.json does not`);
    if (placeholders(text) !== placeholders(STRINGS[key])) throw new Error(`strings: ${code}.json "${key}" must keep the placeholders of the English: ${STRINGS[key]}`);
  }
}

const po = (s) => `"${s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n')}"`;
/** A GNU .mo file: the header, then each translated entry (context EOT msgid → msgstr), sorted, as gettext reads it. */
export function mo(entries) {
  const enc = (s) => Buffer.from(s, 'utf8');
  const sorted = entries.map(([k, v]) => [enc(k), enc(v)]).sort((a, b) => Buffer.compare(a[0], b[0]));
  const n = sorted.length;
  const tableAt = 28;
  let data = tableAt + n * 16;
  const head = Buffer.alloc(tableAt + n * 16);
  head.writeUInt32LE(0x950412de, 0);
  head.writeUInt32LE(0, 4);
  head.writeUInt32LE(n, 8);
  head.writeUInt32LE(tableAt, 12);
  head.writeUInt32LE(tableAt + n * 8, 16);
  head.writeUInt32LE(0, 20);
  head.writeUInt32LE(0, 24);
  const blobs = [];
  for (const [col, table] of [[0, tableAt], [1, tableAt + n * 8]]) {
    sorted.forEach((pair, i) => {
      head.writeUInt32LE(pair[col].length, table + i * 8);
      head.writeUInt32LE(data, table + i * 8 + 4);
      blobs.push(pair[col], Buffer.from([0]));
      data += pair[col].length + 1;
    });
  }
  return Buffer.concat([head, ...blobs]);
}


export function build() {
const header = '// Generated by packages/html/strings/build.mjs from packages/html/strings/*.json. Do not edit.\n';
const json = (v) => JSON.stringify(v, null, 2);

writeFileSync(join(packages, 'react', 'src', 'strings.ts'), `${header}
/** GGDS's own text in English, by key. A component's strings prop takes any of these, to translate or reword it. */
export const STRINGS = ${json(STRINGS)} as const;

export type GGDSStringKey = keyof typeof STRINGS;
export type GGDSStrings = Record<GGDSStringKey, string>;

export interface Language { code: string; name: string; own: string; checked: boolean }

/** The languages GGDS's text is prepared for. checked: false until a speaker has confirmed it. */
export const LANGUAGES: readonly Language[] = ${json(LANGUAGES)};

/** Each language's translations so far; a missing key falls back to English. */
export const TRANSLATIONS: Readonly<Record<string, Partial<GGDSStrings>>> = ${json(TRANSLATIONS)};

/** GGDS's text in a language (its lang code), English where it has no translation yet. */
export function stringsFor(lang: string): GGDSStrings {
  return { ...STRINGS, ...TRANSLATIONS[lang] };
}
`);

writeFileSync(join(packages, 'astro', 'src', 'strings.mjs'), `${header}
/** GGDS's own text in English, by key. A component's strings prop takes any of these, to translate or reword it. */
export const STRINGS = Object.freeze(${json(STRINGS)});

/** The languages GGDS's text is prepared for. checked: false until a speaker has confirmed it. */
export const LANGUAGES = Object.freeze(${json(LANGUAGES)});

/** Each language's translations so far; a missing key falls back to English. */
export const TRANSLATIONS = Object.freeze(${json(TRANSLATIONS)});

/** GGDS's text in a language (its lang code), English where it has no translation yet. */
export const stringsFor = (lang) => ({ ...STRINGS, ...TRANSLATIONS[lang] });

const esc = (s) => String(s ?? '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
/** A string as HTML for set:html: its text escaped, each {name} replaced by html[name] (already HTML) or text[name]. */
export const fillHtml = (template, html = {}, text = {}) =>
  esc(template).replace(/\\{(\\w+)\\}/g, (m, k) => (k in html ? html[k] : k in text ? esc(text[k]) : m));
`);

// Django: the English and the language list, read by ggds_django/strings.py, and a gettext catalogue per language.
const app = join(packages, 'django', 'src', 'ggds_django');
writeFileSync(join(app, 'strings.json'), `${json({ strings: STRINGS, languages: LANGUAGES })}\n`);
rmSync(join(app, 'locale'), { recursive: true, force: true });

for (const { code, name } of LANGUAGES.filter((l) => l.code !== 'en')) {
  const t = TRANSLATIONS[code];
  const dir = join(app, 'locale', code, 'LC_MESSAGES');
  mkdirSync(dir, { recursive: true });
  const meta = `Project-Id-Version: ggds-django\nLanguage: ${code}\nMIME-Version: 1.0\nContent-Type: text/plain; charset=UTF-8\nContent-Transfer-Encoding: 8bit\n`;
  const body = Object.entries(STRINGS).map(([key, en]) => `msgctxt ${po(key)}\nmsgid ${po(en)}\nmsgstr ${po(t[key] ?? '')}\n`).join('\n');
  writeFileSync(join(dir, 'django.po'), `# GGDS's own text in ${name}. Generated from packages/html/strings/${code}.json: translate there, not here.\nmsgid ""\nmsgstr ""\n${meta.split('\n').filter(Boolean).map((l) => po(`${l}\n`)).join('\n')}\n\n${body}`);
  writeFileSync(join(dir, 'django.mo'), mo([['', meta], ...Object.entries(t).map(([key, text]) => [`${key}\x04${STRINGS[key]}`, text])]));
}

const done = Object.entries(TRANSLATIONS).map(([c, t]) => `${c} ${Object.keys(t).length}/${Object.keys(STRINGS).length}`).join(', ');
console.log(`strings: ${Object.keys(STRINGS).length} texts; translated: ${done}`);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) build();
