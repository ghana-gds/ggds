// Builds @ggds/css:
//   dist/ggds.css             tokens + base + components (one <link> for most sites)
//   dist/ggds-components.css  base + components only, for sites that load @ggds/tokens separately
//   dist/core.css             tokens + base only; then add the components a site uses, one file each:
//   dist/components/<name>.css   one component, in its layer (for sites that load only what they use)
//   dist/base.css             base only (core.css without the tokens)
//   dist/components.json      which component styles each class, for subset.mjs (one file holding only what a site uses)
// Styles sit in the cascade layers ggds.base, ggds.components and ggds.utilities (layout), so a site's own unlayered CSS always wins
// without !important. Every file also has a minified copy, <name>.min.css. The published CSS has no dependencies;
// the build uses Lightning CSS (a dev dependency) to minify.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { transform } from 'lightningcss';

const { version } = JSON.parse(readFileSync(join(dirname(fileURLToPath(import.meta.url)), 'package.json'), 'utf8'));
const banner = `/*! GGDS ${version} | Apache-2.0 | https://github.com/ghana-gds/ggds */\n`;
const minifyCss = (filename, code) => banner + transform({ filename, code, minify: true }).code;
const kb = (bytes) => `${(bytes / 1024).toFixed(1)} KB`;

const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, 'src');
const dist = join(here, 'dist');
const tokensCss = join(here, '..', 'tokens', 'dist', 'tokens.css');

// Order matters only within a layer; keep it stable and readable.
export const COMPONENTS = [
  'skip-link', 'cookie-banner', 'banner', 'phase-banner', 'header', 'footer', 'navigation', 'button', 'field', 'password-input', 'error-summary',
  'date-input', 'progress', 'summary-list', 'panel', 'notice', 'tag', 'icon', 'card', 'table', 'meter', 'key-figures',
  'timeline', 'steps', 'task-list', 'dialog', 'disclosure', 'prose', 'feedback', 'hero', 'page-heading', 'tab-bar', 'layout',
];
// Layout classes go in their own layer after the components, so a layout class on a component wins over the
// component's own spacing without !important. A site's unlayered CSS still wins over every layer.
export const UTILITIES = ['layout'];
export const LAYERS = '@layer ggds.base, ggds.components, ggds.utilities;';
const layerOf = (c) => (UTILITIES.includes(c) ? 'ggds.utilities' : 'ggds.components');

const read = (p) => readFileSync(p, 'utf8').trim();
const base = read(join(src, 'base.css'));
const block = (layer) => COMPONENTS.filter((c) => layerOf(c) === layer).map((c) => `/* ${c} */\n${read(join(src, 'components', `${c}.css`))}`).join('\n\n');

const layered = `${LAYERS}\n\n@layer ggds.base {\n${base}\n}\n\n@layer ggds.components {\n${block('ggds.components')}\n}\n\n@layer ggds.utilities {\n${block('ggds.utilities')}\n}\n`;
const header = '/* GGDS: Ghana Government Design System. Generated by @ggds/css build.mjs. Do not edit. */\n';

mkdirSync(dist, { recursive: true });
writeFileSync(join(dist, 'ggds-components.css'), header + layered);
writeFileSync(join(dist, 'ggds.css'), `${header}${read(tokensCss).replace(/^\/\*.*?\*\/\n/, '')}\n\n${layered}`);
// Pick and choose: core.css, then one file per component. Same layers, so the result is the same as ggds.css.
mkdirSync(join(dist, 'components'), { recursive: true });
writeFileSync(join(dist, 'core.css'), `${header}${read(tokensCss).replace(/^\/\*.*?\*\/\n/, '')}\n\n${LAYERS}\n\n@layer ggds.base {\n${base}\n}\n`);
for (const c of COMPONENTS) {
  writeFileSync(join(dist, 'components', `${c}.css`), `${header}@layer ${layerOf(c)} {\n${read(join(src, 'components', `${c}.css`))}\n}\n`);
}
// base.css: core.css without the tokens, for a site that loads @ggds/tokens separately and picks its components.
writeFileSync(join(dist, 'base.css'), `${header}${LAYERS}\n\n@layer ggds.base {\n${base}\n}\n`);

// components.json: what subset.mjs needs to build a stylesheet holding only the components a site uses.
// classes maps each block class (ggds-field, from .ggds-field__hint too) to the components that style it. A class
// several files mention belongs to the one named after it (ggds-field → field, ggds-table-wrap → table), so using
// it does not pull in every component that happens to style it; a class only one file mentions belongs to that one.
const owners = {};
for (const c of COMPONENTS) {
  for (const m of read(join(src, 'components', `${c}.css`)).matchAll(/\.(ggds-[a-z0-9-]+?)(?=__|--|[^a-z0-9-]|$)/g)) {
    (owners[m[1]] ??= new Set()).add(c);
  }
}
const classes = Object.fromEntries(Object.entries(owners).sort(([a], [b]) => a.localeCompare(b)).map(([cls, set]) => {
  const named = [...set].filter((c) => cls === `ggds-${c}` || cls.startsWith(`ggds-${c}-`));
  const prefixed = [...set].filter((c) => cls.startsWith(`ggds-${c}`)); // ggds-fieldset → field
  return [cls, named.length ? named : prefixed.length ? prefixed : [...set]];
}));
writeFileSync(join(dist, 'components.json'), `${JSON.stringify({ version, components: COMPONENTS, layers: Object.fromEntries(COMPONENTS.map((c) => [c, layerOf(c)])), classes }, null, 1)}\n`);

// A minified copy of every file, <name>.min.css, for production. Only whitespace and comments go: no targets are
// set, so Lightning CSS changes no syntax and the result works in exactly the browsers the readable file does.
const files = ['ggds.css', 'ggds-components.css', 'core.css', 'base.css', ...COMPONENTS.map((c) => `components/${c}.css`)];
let full = 0;
let min = 0;
for (const f of files) {
  const code = readFileSync(join(dist, f));
  const out = minifyCss(f, code);
  writeFileSync(join(dist, f.replace(/\.css$/, '.min.css')), out);
  if (f === 'ggds.css') [full, min] = [code.length, out.length];
}
console.log(`css: base + ${COMPONENTS.length} components → ${dist} (ggds.css ${kb(full)}, minified ${kb(min)})`);
