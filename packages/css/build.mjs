// Builds @ggds/css:
//   dist/ggds.css             tokens + base + components (one <link> for most sites)
//   dist/ggds-components.css  base + components only, for sites that load @ggds/tokens separately
//   dist/core.css             tokens + base only; then add the components a site uses, one file each:
//   dist/components/<name>.css   one component, in its layer (for sites that load only what they use)
// Styles sit in the cascade layers ggds.base and ggds.components, so a site's own unlayered CSS always wins
// without !important. Every file also has a minified copy, <name>.min.css. The published CSS has no dependencies;
// the build uses Lightning CSS (a dev dependency) to minify.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { transform } from 'lightningcss';

const { version } = JSON.parse(readFileSync(join(dirname(fileURLToPath(import.meta.url)), 'package.json'), 'utf8'));
const banner = `/*! GGDS ${version} | Apache-2.0 | https://github.com/ghana-gds/ggds */\n`;
const minifyCss = (filename, code) => banner + transform({ filename, code, minify: true }).code;
const kb = (bytes) => `${(bytes / 1024).toFixed(1)} KB`;

const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, 'src');
const dist = join(here, 'dist');
const tokensCss = join(here, '..', 'tokens', 'dist', 'tokens.css');

// Order matters only within a layer; keep it stable and readable.
export const COMPONENTS = [
  'skip-link', 'banner', 'header', 'footer', 'navigation', 'button', 'field', 'error-summary',
  'notice', 'tag', 'card', 'table', 'disclosure', 'prose', 'hero', 'tab-bar',
];

const read = (p) => readFileSync(p, 'utf8').trim();
const base = read(join(src, 'base.css'));
const components = COMPONENTS.map((c) => `/* ${c} */\n${read(join(src, 'components', `${c}.css`))}`).join('\n\n');

const layered = `@layer ggds.base, ggds.components;\n\n@layer ggds.base {\n${base}\n}\n\n@layer ggds.components {\n${components}\n}\n`;
const header = '/* GGDS: Ghana Government Design System. Generated by @ggds/css build.mjs. Do not edit. */\n';

mkdirSync(dist, { recursive: true });
writeFileSync(join(dist, 'ggds-components.css'), header + layered);
writeFileSync(join(dist, 'ggds.css'), `${header}${read(tokensCss).replace(/^\/\*.*?\*\/\n/, '')}\n\n${layered}`);
// Pick and choose: core.css, then one file per component. Same layers, so the result is the same as ggds.css.
mkdirSync(join(dist, 'components'), { recursive: true });
writeFileSync(join(dist, 'core.css'), `${header}${read(tokensCss).replace(/^\/\*.*?\*\/\n/, '')}\n\n@layer ggds.base, ggds.components;\n\n@layer ggds.base {\n${base}\n}\n`);
for (const c of COMPONENTS) {
  writeFileSync(join(dist, 'components', `${c}.css`), `${header}@layer ggds.components {\n${read(join(src, 'components', `${c}.css`))}\n}\n`);
}

// A minified copy of every file, <name>.min.css, for production. Only whitespace and comments go: no targets are
// set, so Lightning CSS changes no syntax and the result works in exactly the browsers the readable file does.
const files = ['ggds.css', 'ggds-components.css', 'core.css', ...COMPONENTS.map((c) => `components/${c}.css`)];
let full = 0;
let min = 0;
for (const f of files) {
  const code = readFileSync(join(dist, f));
  const out = minifyCss(f, code);
  writeFileSync(join(dist, f.replace(/\.css$/, '.min.css')), out);
  if (f === 'ggds.css') [full, min] = [code.length, out.length];
}
console.log(`css: base + ${COMPONENTS.length} components → ${dist} (ggds.css ${kb(full)}, minified ${kb(min)})`);
