// The kinds of institution the website starter can be, each with the words it starts from: its homepage question,
// its services (each with the words of its own page), fees, news, publications, jobs, its "About us" and the wording
// of its forms. An institution changes every word in the website builder; these are only where it starts, so they
// are written as good examples for that kind of institution, in plain words. Everything here is plain text (the
// starter escapes it): no HTML. Runs in the browser and in Node, so no imports.
//
// A service: title, summary (one line, on its card), group (its heading on the Services page), task (on the
// homepage as a common task), online (it has the online application: start page, form, check your answers,
// confirmation; one service at most), and the words of its page: who, need (lists, one item a line), time, cost,
// how (paragraphs). An online service also has options (what people choose on the form) and steps (what happens
// after they apply: [title, when]).

