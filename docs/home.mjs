// The documentation homepage's interactive sections: GGDS shows what it promises instead of saying it.
//
//   themeSection   Choose an institution and the whole page takes its colours: the header line, the hero, the
//                  drawing and the footer. Buttons, links and fields stay the same. Radio buttons and CSS :has()
//                  only, so it works without JavaScript; the colours glide between themes through registered custom
//                  properties (@property), except under prefers-reduced-motion. With JavaScript, home.js saves
//                  the choice and theme-pref.js applies it to every documentation page ([data-ggds-theme] on <html>);
//                  the :has() rules are then switched off so the attribute alone sets the colour.
//   tryForm        A real GGDS form: leave it empty or type something wrong to see the error summary and the
//                  field's error, then a confirmation panel. Needs home.js; without it, a link to the components.
//   screensSection A real example page in a frame that you resize from a 320px phone to a wide screen. With home.js
//                  a slider and presets; without it, the page at the width of the screen.
//
// Strict CSP: no inline styles or scripts. home.js sets sizes through the CSSOM only.
import { esc } from './parts.mjs';

/** The theme picker and its live preview. themes: [{ slug, name, shortName, accent, deep }], default first. */
export function themeSection(themes) {
  const [first] = themes;
  const options = themes.map((t) => `
  <input class="home-theme__input" type="radio" name="home-theme" id="home-theme-${t.slug}" value="${t.slug}"${t === first ? ' checked' : ''}>
  <label class="home-theme__chip" for="home-theme-${t.slug}"><span class="home-theme__dot home-theme__dot--${t.slug}" aria-hidden="true"></span>${esc(t.shortName)}<span class="ggds-visually-hidden">: ${esc(t.name)}</span></label>`).join('');
  const names = themes.map((t) => `<span class="home-theme__name" data-theme="${t.slug}"><strong>${esc(t.name)}</strong> <code>${t.accent}</code> <code>${t.deep}</code></span>`).join('');
  return `
<section class="docs-home-section home-theme" aria-labelledby="home-theme-h">
<div class="home-theme__grid">
<div class="home-theme__text">
<h2 id="home-theme-h">One design system, every institution</h2>
<p class="ggds-measure">Choose an institution. This whole page changes to its colour: the line under the header, the hero, the drawing and the footer. Buttons, links and form fields stay exactly the same, so people know how to use every government website.</p>
<fieldset class="home-theme__picker">
<legend class="home-theme__legend">See this page in an institution's theme</legend>
<div class="home-theme__options">${options}
</div>
</fieldset>
<p class="home-theme__now" aria-hidden="true">${names}</p>
<p><a class="ggds-with-icon" href="themes.html#make-a-theme">Make a theme from your own colour<span aria-hidden="true"> →</span></a></p>
</div>
<div class="home-theme__demo" aria-hidden="true">
<div class="home-theme__compare">
<div class="docs-theme home-theme__preview">
  <div class="docs-theme__header"><span class="docs-theme__name">Your institution</span></div>
  <div class="docs-theme__hero"><p class="docs-theme__purpose">Changes with the theme</p><p class="docs-theme__title">What do you need help with?</p></div>
  <div class="docs-theme__body"><span class="ggds-button">Start now</span> <span class="home-theme__link">Never changes</span></div>
  <div class="docs-theme__footer">The footer changes too</div>
</div>
</div>
</div>
</div>
</section>`;
}

/** The picker's CSS: one rule per theme on :root, so every institution surface follows. */
export function themeCss(themes) {
  const rule = (t) => `:root:not([data-ggds-theme]):has(#home-theme-${t.slug}:checked) { --ggds-color-institution: ${t.accent}; --ggds-color-institution-deep: ${t.deep}; }
:root:has(#home-theme-${t.slug}:checked) .home-theme__name[data-theme="${t.slug}"] { display: inline; }
.home-theme__dot--${t.slug} { background: ${t.accent}; }`;
  return `/* Generated by docs/home.mjs: the homepage's theme picker. */
${themes.map(rule).join('\n')}
`;
}

